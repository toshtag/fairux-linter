#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isBuiltinJurisdictionId, isSemver } from "../../core/dist/index.js";
import { fairuxBuiltinRulePack } from "../dist/index.js";
import {
  collectRuntimeRuleMetadata,
  compareCanonicalId,
  validateReviewFoundation,
} from "./review-validation.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const SOURCES_PATH = join(ROOT, "packages/rules/reviews/official-sources.json");
const REVIEWS_PATH = join(ROOT, "packages/rules/reviews/built-in-rule-reviews.json");
const GENERATED_RUNTIME_PATH = join(ROOT, "packages/rules/src/generated/reviewed-governance.ts");
const RUNTIME_SOURCE_KINDS = new Set(["direct", "contextual", "standard"]);

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function toTsLiteral(value) {
  return JSON.stringify(value, null, 2).replaceAll('"', '"').replace(/\n/g, "\n");
}

function formatGenerated(path, contents, rootDir) {
  if (!path.endsWith(".json") && !path.endsWith(".ts")) return contents;
  const result = spawnSync("pnpm", ["exec", "biome", "format", "--stdin-file-path", path], {
    cwd: rootDir,
    input: contents,
    encoding: "utf8",
  });
  if (result.status !== 0) {
    throw new Error(result.stderr || `Biome failed while formatting ${path}`);
  }
  return result.stdout;
}

function currentRuntimeSource(review, sourcesById) {
  const source = sourcesById.get(review.sourceId);
  if (!source) throw new Error(`Unknown official source ${review.sourceId}`);
  if (source.catalogMetadata.publicationStatus !== "current") return undefined;
  if (!RUNTIME_SOURCE_KINDS.has(review.supportKind)) return undefined;
  return {
    id: source.id,
    title: source.identity.title,
    publisher: source.identity.publisher,
    url: source.identity.url,
    reviewedAt: review.reviewedAt,
    jurisdictions: review.jurisdictions,
  };
}

export function reviewedGovernance(records, sourcesById) {
  const entries = {};
  for (const rule of [...records.rules].sort((left, right) =>
    compareCanonicalId(left.ruleId, right.ruleId),
  )) {
    const officialSources = rule.officialSourceReviews
      .map((review) => currentRuntimeSource(review, sourcesById))
      .filter(Boolean)
      .sort((left, right) => compareCanonicalId(left.id, right.id));
    entries[rule.ruleId] = {
      maturity: rule.maturity,
      jurisdictions: rule.ruleJurisdictions,
      officialSources,
      knownLimitations: rule.reviewNotes.knownLimitations,
    };
  }
  return entries;
}

function runtimeSource(governance) {
  return `// Generated by packages/rules/scripts/generate-reviewed-governance.mjs. Do not edit by hand.
import type { RuleMeta } from "@fairux/core";

type ReviewedRuleGovernance = Pick<
  RuleMeta,
  "maturity" | "jurisdictions" | "officialSources" | "knownLimitations"
>;

export const reviewedGovernanceByRuleId = Object.freeze(${toTsLiteral(
    governance,
  )} as const satisfies Record<string, ReviewedRuleGovernance>);
`;
}

export function renderReviewedGovernanceArtifacts(input) {
  const rootDir = input.rootDir ?? ROOT;
  const runtimeRules =
    input.runtimeRules ?? collectRuntimeRuleMetadata(fairuxBuiltinRulePack.rules);
  const result = validateReviewFoundation({
    sourceCatalog: input.sourceCatalog,
    reviewRecords: input.reviewRecords,
    runtimeRules,
    isBuiltinJurisdictionId: input.isBuiltinJurisdictionId ?? isBuiltinJurisdictionId,
    isSemver: input.isSemver ?? isSemver,
    rootDir,
    requireApprovedStable: input.requireApprovedStable,
  });
  if (!result.ok) {
    throw new Error(`Review governance input validation failed:\n${result.errors.join("\n")}`);
  }

  const sourcesById = new Map(input.sourceCatalog.sources.map((source) => [source.id, source]));
  const governance = reviewedGovernance(input.reviewRecords, sourcesById);
  return {
    summary: result.summary,
    artifacts: [
      {
        path: input.outputPath ?? GENERATED_RUNTIME_PATH,
        contents: runtimeSource(governance),
      },
    ],
  };
}

function atomicWrite(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  const tempPath = join(dirname(path), `.${basename(path)}.${process.pid}.tmp`);
  writeFileSync(tempPath, contents, "utf8");
  renameSync(tempPath, path);
}

function writeOrCheckArtifacts(artifacts, options) {
  let drift = false;
  for (const artifact of artifacts) {
    const formatted = formatGenerated(artifact.path, artifact.contents, options.rootDir);
    if (options.checkOnly) {
      let current;
      try {
        current = readFileSync(artifact.path, "utf8");
      } catch {
        current = undefined;
      }
      if (current !== formatted) {
        console.error(`${artifact.path} is not up to date. Run pnpm rules:governance:write.`);
        drift = true;
      }
    } else {
      const current = (() => {
        try {
          return readFileSync(artifact.path, "utf8");
        } catch {
          return undefined;
        }
      })();
      if (current !== formatted) atomicWrite(artifact.path, formatted);
    }
  }
  if (drift) process.exitCode = 1;
}

function parseMode(argv) {
  const checkOnly = argv.includes("--check");
  const write = argv.includes("--write");
  if (checkOnly === write) {
    throw new Error("Usage: generate-reviewed-governance.mjs --write|--check");
  }
  return { checkOnly };
}

function main() {
  const mode = parseMode(process.argv.slice(2));
  const rendered = renderReviewedGovernanceArtifacts({
    rootDir: ROOT,
    sourceCatalog: readJson(SOURCES_PATH),
    reviewRecords: readJson(REVIEWS_PATH),
  });
  writeOrCheckArtifacts(rendered.artifacts, { rootDir: ROOT, checkOnly: mode.checkOnly });
  if (!mode.checkOnly && process.exitCode !== 1) {
    console.log(
      `Generated reviewed governance for ${rendered.summary.reviewRecordCount} rules and ${rendered.summary.sourceIdentityCount} source identities.`,
    );
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
