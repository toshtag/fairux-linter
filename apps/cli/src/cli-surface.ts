/**
 * What a description needs that this file cannot know.
 *
 * One option's help text lists the Risk Index models, and those come from `@fairux/rules` rather
 * than from the command line — a model arriving is a rule-set change, not a CLI change. Passing it
 * in keeps this module free of the engine, which is what lets the inventory generator load it
 * without building anything.
 */
export interface CliHelpContext {
  readonly riskIndexModelVersions: readonly string[];
  readonly defaultRiskIndexModel: string;
}

export interface CliOptionSpec {
  /** Exactly what Commander is given, and the only place the flag's spelling is written. */
  readonly flags: string;
  readonly description: string | ((context: CliHelpContext) => string);
  /** Supplied to Commander, and recorded in the inventory: changing one changes what a run does. */
  readonly defaultValue?: string | boolean;
  /** The values this option accepts, when the CLI is the thing that decides them. */
  readonly values?: readonly string[];
  /** Repeating the flag collects, rather than replacing. */
  readonly repeatable?: boolean;
}

export interface CliArgumentSpec {
  /** In Commander's own notation, so required and variadic are its answer rather than ours. */
  readonly name: string;
  readonly description: string;
}

export interface CliCommandSpec {
  readonly name: string;
  readonly description?: string;
  readonly argument?: CliArgumentSpec;
  readonly options: readonly CliOptionSpec[];
}

/** `a | b | c`, the form every format description in this CLI already uses. */
function pipeList(values: readonly string[]): string {
  return values.join(" | ");
}

