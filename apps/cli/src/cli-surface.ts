/** Repeating a flag collects its values; the first one starts the list. */
function collect(value: string, previous: string[] = []): string[] {
  return [...previous, value];
}

/**
 * Attach every command and option above to a program, and hand back the commands by name.
 *
 * `index.ts` adds an action to each; the inventory generator adds none and reads the result. One
 * wiring, so the artifact describes the program that ships rather than a second program built to
 * resemble it.
 */
export function applyCliSurface(
  program: Command,
  context: CliHelpContext,
): ReadonlyMap<string, Command> {
  const commands = new Map<string, Command>();
  for (const spec of CLI_COMMANDS) {
    const command = program.command(spec.name);
    if (spec.description) command.description(spec.description);
    if (spec.argument) command.argument(spec.argument.name, spec.argument.description);
    for (const option of spec.options) {
      const description =
        typeof option.description === "function" ? option.description(context) : option.description;
      if (option.repeatable) command.option(option.flags, description, collect);
      else if (option.defaultValue !== undefined)
        command.option(option.flags, description, option.defaultValue);
      else command.option(option.flags, description);
    }
    commands.set(spec.name, command);
  }
  return commands;
}
