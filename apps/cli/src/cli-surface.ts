import type { Command } from "commander";

/**
 * The command line as data, declared once and read by everything that depends on it.
 *
 * `docs/reference/compatibility.md` calls the CLI's flags and exit codes a public surface, and the
 * SDK's half of that promise is kept by a committed inventory: a name leaving
 * `docs/generated/sdk-api-inventory.json` is a diff somebody has to argue for. The command line had
 * no equivalent. It was fifteen `.option()` calls in `index.ts`, and removing one looked exactly
 * like editing one.
 *
 * So the flags live here, and three readers consume this file rather than each other:
 *
 * - {@link applyCliSurface} builds the Commander program `index.ts` runs;
 * - `scan-options.ts` validates against the same value sets the help text prints;
 * - `scripts/generate-cli-inventory.mjs` builds the same program with no actions attached and
 *   records what Commander made of it.
 *
 * The inventory is generated by giving these strings to Commander and reading the `Option` objects
 * back, rather than by matching `-f, --format <format>` with a regular expression written here. A
 * flag string means whatever the library parsing it decides, and a second parser would eventually
 * disagree with the first about a corner of the syntax nobody tested.
 *
 * What is **not** here: help formatting, the order options happen to appear in a paragraph, and the
 * action bodies. The inventory records none of those, on purpose — a contract that pinned the
 * wording of a description would fail on a typo fix and say "breaking change".
 */

